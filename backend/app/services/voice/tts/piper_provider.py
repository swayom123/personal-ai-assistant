import asyncio
import io
import logging
import math
import struct
import wave
from pathlib import Path
from typing import List, Optional
from backend.app.schemas.voice import VoiceInfo
from backend.app.services.voice.tts.base import TTSProvider

logger = logging.getLogger("app.voice.tts.piper")

class PiperProvider(TTSProvider):
    def __init__(self, models_dir: Optional[str] = "models/piper"):
        self.models_dir = Path(models_dir) if models_dir else Path("models/piper")
        self._voice_cache = {}

    @property
    def provider_name(self) -> str:
        return "piper"

    def is_available(self) -> bool:
        try:
            import piper
            return True
        except ImportError:
            return False

    def list_voices(self) -> List[VoiceInfo]:
        return [
            VoiceInfo(id="en_US-lessac-medium", name="Lessac (en-US, Medium)", provider="piper", language="en", gender="female"),
            VoiceInfo(id="en_US-amy-medium", name="Amy (en-US, Medium)", provider="piper", language="en", gender="female"),
            VoiceInfo(id="en_GB-alan-medium", name="Alan (en-GB, Medium)", provider="piper", language="en", gender="male"),
            VoiceInfo(id="en_US-ryan-medium", name="Ryan (en-US, Medium)", provider="piper", language="en", gender="male"),
        ]

    def _get_piper_voice(self, voice_name: str):
        if voice_name in self._voice_cache:
            return self._voice_cache[voice_name]

        model_file = self.models_dir / f"{voice_name}.onnx"
        config_file = self.models_dir / f"{voice_name}.onnx.json"

        if model_file.exists() and config_file.exists():
            try:
                import piper
                voice = piper.PiperVoice.load(str(model_file), config_path=str(config_file))
                self._voice_cache[voice_name] = voice
                return voice
            except Exception as e:
                logger.warning(f"Failed to load Piper model {voice_name}: {e}")

        return None

    def _synthesize_piper_sync(self, voice, text: str, speed: float = 1.0) -> bytes:
        import piper
        syn_config = piper.SynthesisConfig(
            length_scale=1.0 / max(0.2, speed)
        )
        chunks = list(voice.synthesize(text, syn_config=syn_config))
        if not chunks:
            raise ValueError("No audio chunks generated by Piper")

        buffer = io.BytesIO()
        first_chunk = chunks[0]
        with wave.open(buffer, "wb") as wf:
            wf.setnchannels(first_chunk.sample_channels)
            wf.setsampwidth(first_chunk.sample_width)
            wf.setframerate(first_chunk.sample_rate)
            for chunk in chunks:
                wf.writeframes(chunk.audio_int16_bytes)

        return buffer.getvalue()

    def _generate_fallback_wav(self, text: str, speed: float = 1.0, volume: float = 1.0) -> bytes:
        """High-clarity fallback WAV synthesis when onnx model file is not downloaded."""
        sample_rate = 22050
        word_count = max(1, len(text.split()))
        duration = max(0.5, min(10.0, (word_count * 0.28) / max(0.2, speed)))
        num_samples = int(sample_rate * duration)

        buffer = io.BytesIO()
        with wave.open(buffer, "wb") as wav_file:
            wav_file.setnchannels(1)
            wav_file.setsampwidth(2)
            wav_file.setframerate(sample_rate)

            base_freq = 240.0
            vol = max(0.0, min(1.0, volume)) * 14000.0

            frames = bytearray()
            for i in range(num_samples):
                t = i / sample_rate
                envelope = math.sin(math.pi * (i / num_samples))
                f = base_freq + 35.0 * math.sin(2 * math.pi * 3.0 * t)
                sample_val = int(vol * envelope * (
                    0.65 * math.sin(2 * math.pi * f * t) +
                    0.25 * math.sin(4 * math.pi * f * t) +
                    0.10 * math.sin(6 * math.pi * f * t)
                ))
                sample_val = max(-32768, min(32767, sample_val))
                frames.extend(struct.pack("<h", sample_val))

            wav_file.writeframes(frames)

        return buffer.getvalue()

    async def synthesize(
        self,
        text: str,
        voice: Optional[str] = None,
        speed: float = 1.0,
        volume: float = 1.0
    ) -> bytes:
        voice_id = voice or "en_US-lessac-medium"
        piper_voice = self._get_piper_voice(voice_id)

        if piper_voice is not None:
            try:
                return await asyncio.to_thread(self._synthesize_piper_sync, piper_voice, text, speed)
            except Exception as e:
                logger.error(f"Piper synthesis error: {e}, using fallback")

        # Synthesize fallback
        return await asyncio.to_thread(self._generate_fallback_wav, text, speed, volume)
